// Сенсорное устройство — телефон или планшет: основной указатель «грубый» (палец).
// Ноутбук с сенсорным экраном сюда не попадает — основной указатель у него мышь.
// Нужно, чтобы не ставить фокус в поле поиска при открытии окна: на телефоне и
// планшете фокус сразу вызывает экранную клавиатуру на пол-экрана.
export const isTouchDevice = () =>
  typeof window !== 'undefined' && !!window.matchMedia?.('(pointer: coarse)').matches;
