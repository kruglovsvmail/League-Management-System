// Публичный эндпоинт отдаёт судейскую бригаду ключами 'main-1' / 'linesman-1' /
// 'commentator-1' (см. getPublicGameById). Дефолтная графика ищет head_1/media —
// таких ключей в ответе нет, поэтому её плашки судей и комментатора не появляются
// вообще. Читаем актуальные ключи, старые оставляем как запасной вариант.
export const pickOfficial = (officials, ...keys) => {
  if (!officials) return null;
  for (const k of keys) if (officials[k]) return officials[k];
  return null;
};
