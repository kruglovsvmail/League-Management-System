// --- Геометрия -------------------------------------------------------------
// Все срезы кратны своей глубине по обеим осям, то есть настоящие 45°.

// Прямоугольник со срезанными углами: глубина среза в px, по часовой с левого верхнего.
export const cut = (tl = 0, tr = 0, br = 0, bl = 0) =>
  `polygon(${tl}px 0, calc(100% - ${tr}px) 0, 100% ${tr}px, 100% calc(100% - ${br}px), calc(100% - ${br}px) 100%, ${bl}px 100%, 0 calc(100% - ${bl}px), 0 ${tl}px)`;

// «Лезвие» — срезаны только два нижних угла. Силуэт табло и верхних реек.
export const blade = (d = 30) => cut(0, 0, d, d);

// Шеврон: нижняя кромка сходится углом вниз. Центральный блок табло.
export const chevron = (d = 26) =>
  `polygon(0 0, 100% 0, 100% calc(100% - ${d}px), 50% 100%, 0 calc(100% - ${d}px))`;

// Стрелка вправо/влево — плитки счёта и чипы событий.
export const arrowR = (d = 22) =>
  `polygon(0 0, calc(100% - ${d}px) 0, 100% 50%, calc(100% - ${d}px) 100%, 0 100%)`;
export const arrowL = (d = 22) =>
  `polygon(${d}px 0, 100% 0, 100% 100%, ${d}px 100%, 0 50%)`;

// Тень задаём фильтром на РОДИТЕЛЕ: clip-path обрезал бы box-shadow вместе с фоном,
// а drop-shadow повторяет форму среза.
