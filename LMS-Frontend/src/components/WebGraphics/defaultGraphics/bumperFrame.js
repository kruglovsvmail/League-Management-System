// Переход заставки стандартной графики — «Щелчок». 3D-сцена (three.js) с
// шайбой из Blender: design/puck-3d-2026-10-08 → S3
// leagues/default/3d-models/puck.glb. Сама сцена — в ./bumperScene.js.
//
// В эфире 3D НЕ СЧИТАЕТСЯ. Панель один раз собирает переход покадрово в WebM с
// прозрачностью (utils/exportBumperWebm.js), эфир и Stinger в OBS играют
// готовый файл. Поэтому этот файл лёгкий: его без условий импортирует оверлей
// (WebGraphics/BumperOverlay.jsx берёт отсюда SWEEP_MS и COVER_MS), и three.js
// сюда тянуть нельзя — сцена подгружается динамически только при сборке.
//
// СЦЕНАРИЙ (мс)
//      0–550  из точки вдали, по прямой с постоянной скоростью, кувыркаясь
//              на камеру летит шайба с логотипом лиги почти во весь торец
//    550       УДАР РЕБРОМ почти у камеры (шайба ~1100 px): вспышка, круговая
//              волна, встряска. Без линий и стекла — обе версии Сергей
//              отклонил
//    550–1180  шайба отскакивает, делает сальто и застревает в шве: стоит на
//              линии шва логотипом к камере, синий свет канавки — по кромке
//    630–950   по диагонали съезжаются две толстые графитовые плиты с фаской
//              цвета своей команды (хозяева — левая верхняя, гости — правая
//              нижняя), на них
//              «нарисованные» логотипы и названия команд; краска стёрта
//              диагональю, как шлифовка плит, без дыр (логотип лиги на шайбе —
//              сплошная печать с мелкими потёртостями)
//    950       плиты смыкаются: по шву пробегает лезвие, кадр вздрагивает
//   1030–2530  статика: по фаскам бежит синий свет TR, по плитам проходит
//              блик, камера медленно наезжает; под шайбой — плашка дивизиона
//              (название лиги и «Реклама» убраны по просьбе Сергея)
//   2530–2880  шайба разворачивается и улетает в камеру
//   2650–3280  плиты разлетаются по диагонали в свои углы; свет шва вспыхивает
//              на кромках обеих плит и уезжает с ними — шов «рвётся» надвое
//
// Кадр перекрыт наглухо с 950 до ~2650 мс. COVER_MS — внутри этого окна: в
// эту миллисекунду под переходом меняют картинку.
//
// Звука нет — так решил Сергей (12.10.2026): HIT_MS не экспортируется.

export const SWEEP_MS = 3330;
export const COVER_MS = 2200;

export const FRAME_W = 1920;
export const FRAME_H = 1080;

// Покадровая сборка: 30 кадров в секунду, кадр — среднее десяти моментов
// внутри половины интервала между кадрами (размытие в движении).
//
// НЕ 60. Прозрачный WebM — это два потока VP8 (цвет и альфа), и браузерный
// источник OBS декодирует оба процессором. На 60 кадрах в 1080p кадры
// раздвижения весили по 80–105 КБ, декодер не успевал — в эфире был
// микрофриз ровно там (12.10.2026). Источник OBS по умолчанию и так рисует
// 30 кадров, а плавность даёт размытие.
export const FPS = 30;
export const BLUR_SAMPLES = 10;
export const SHUTTER = 0.5;

// Отметки сценария — общие для сцены и описания выше.
export const T = {
  IMPACT: 550,
  SLAB_IN: 630,
  SLAM: 950,
  LAND: 1180,
  OUT: 2530,
  SPLIT: 2650,
  GONE: 3280,
};

/**
 * Готовит сцену один раз до записи: three.js, шайба, текстуры логотипов и
 * подписей. Возвращает ассеты, с которыми работает drawBumperFrame.
 */
export async function prepareBumperAssets(raw, { onProgress } = {}) {
  const { createBumperScene } = await import('./bumperScene.js');
  const scene3d = await createBumperScene(raw, { onProgress });
  return { ...raw, scene3d };
}

export function disposeBumperAssets(assets) {
  assets?.scene3d?.dispose();
}

/**
 * Кадр перехода.
 * @param {CanvasRenderingContext2D} ctx холст FRAME_W × FRAME_H
 * @param {number} p прогресс 0..1 по SWEEP_MS
 * @param {object} assets результат prepareBumperAssets
 */
export function drawBumperFrame(ctx, p, assets = {}) {
  const s = assets.scene3d;
  if (!s) return;
  ctx.drawImage(s.render(p * SWEEP_MS), 0, 0);
}
