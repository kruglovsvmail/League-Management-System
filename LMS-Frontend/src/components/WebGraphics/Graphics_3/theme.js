// Публичный эндпоинт отдаёт бригаду ключами 'main-1' / 'linesman-1' /
// 'commentator-1' (см. getPublicGameById). Старые имена (head_1, media)
// оставлены запасным вариантом — на них была написана прежняя версия этих
// плашек, из-за чего они не появлялись в эфире вообще.
export const pickOfficial = (officials, ...keys) => {
  if (!officials) return null;
  for (const k of keys) if (officials[k]) return officials[k];
  return null;
};

export const formatClock = (s) => {
  if (s === undefined || s === null || isNaN(s) || s < 0) return '0:00';
  return `${Math.floor(s / 60)}:${('0' + (Math.floor(s) % 60)).slice(-2)}`;
};

export const periodLabel = (p) => {
  if (p === 'OT') return 'ОВЕРТАЙМ';
  if (p === 'SO') return 'БУЛЛИТЫ';
  return `${p} ПЕРИОД`;
};

// Стадия и номер матча одной строкой — шапка всех полноэкранных плашек.
export const stageText = (game) => {
  if (!game) return '';
  const isPlayoff = game.stage_type === 'playoff';
  const stage = game.stage_label
    ? String(game.stage_label).toUpperCase()
    : (isPlayoff ? 'ПЛЕЙ-ОФФ' : 'РЕГУЛЯРНЫЙ ЧЕМПИОНАТ');
  const num = isPlayoff ? `МАТЧ ${game.series_number || 1}` : `ТУР ${game.series_number || 1}`;
  return `${stage} · ${num}`;
};
