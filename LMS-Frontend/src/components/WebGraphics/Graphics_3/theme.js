// Стилистика: плоская геометрия, диагонали ровно под 45°, снежинки, ледяная палитра.
// Никаких параллелограммов (skew) как в дефолтной графике — вместо них срезанные под 45°
// углы (clip-path), поэтому все плашки читаются как куски одного диагонального паттерна.

export const TFH = {
  navyDeep: '#061530', // фон подвала / самых тёмных блоков
  navy: '#0A1F44',     // основной фон плашек
  navyMid: '#102C5E',  // вторичные блоки внутри плашки
  navyLine: '#1B3A72', // разделители, тонкие рамки
  blue: '#29A9E1',     // акцент лиги (заголовки, активные состояния)
  blueDeep: '#0F83BD', // тот же акцент, что --acc на сайте ТГОО «Федерация хоккея»
  blueSoft: '#7FCBEE',
  ice: '#D6DCE3',      // основной светлый текст на навy
  iceDim: '#8C9AAC',   // подписи, второстепенный текст
  white: '#FFFFFF',
};

// Прямоугольник со срезанными под 45° углами. Аргументы — глубина среза в px
// для каждого угла по часовой стрелке начиная с левого верхнего.
export const cut = (tl = 0, tr = 0, br = 0, bl = 0) =>
  `polygon(${tl}px 0, calc(100% - ${tr}px) 0, 100% ${tr}px, 100% calc(100% - ${br}px), calc(100% - ${br}px) 100%, ${bl}px 100%, 0 calc(100% - ${bl}px), 0 ${tl}px)`;

// Диагональ по всей плашке: срезаны только левый верхний и правый нижний углы —
// фирменная форма всех крупных плашек этого оверлея.
export const cutDiag = (size = 56) => cut(size, 0, size, 0);

// Тень задаётся фильтром на РОДИТЕЛЕ, а не box-shadow на самой плашке:
// clip-path обрезает box-shadow вместе с фоном, drop-shadow же повторяет форму среза.
export const dropShadow = (strength = 'lg') => ({
  lg: 'drop-shadow(0 30px 60px rgba(0,0,0,0.55)) drop-shadow(0 0 1px rgba(41,169,225,0.35))',
  md: 'drop-shadow(0 16px 32px rgba(0,0,0,0.5))',
  sm: 'drop-shadow(0 8px 18px rgba(0,0,0,0.45))',
}[strength]);

// Диагональная штриховка 45° — базовая текстура фона. step — период полосы в px.
export const stripes = (color = 'rgba(255,255,255,0.045)', step = 26, ratio = 0.5) =>
  `repeating-linear-gradient(45deg, ${color} 0 ${step * ratio}px, transparent ${step * ratio}px ${step}px)`;
