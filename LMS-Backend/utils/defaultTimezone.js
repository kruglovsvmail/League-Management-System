// Часовой пояс "по умолчанию", который используется там, где системе нужно однозначно
// определить календарный день/время, а привязать это решение не к чему — нет ни
// конкретной арены со своей таймзоной, ни устройства конкретного пользователя, которое
// можно спросить (как это делается в Team Room для событий с ручным вводом локации —
// см. Team-Room/TR-Frontend/src/components/Manager/ArenaSelector.jsx).
//
// Пример: сроки дивизиона в LMS ("Заявки", "Трансферы") — это одно правило на весь
// дивизион сразу для всех городов и команд, оно не привязано к конкретному месту.
// Чтобы дата "10 сентября", введённая организатором, означала одно и то же для всех,
// её нужно к чему-то жёстко привязать — и в качестве этого эталона выбрана Москва
// (исторически так уже было сделано в других частях проекта, см. CLUB_TIMEZONE в
// LMS-Backend/controllers/metricsController.js, а также TR-Backend/services/pushService.js
// и другие места с фолбэком 'Europe/Moscow').
//
// Это НЕ таймзона конкретной арены/события и не привязана к пользователю — если нужна
// таймзона реального места (матч, тренировка), используй значение из таблицы arenas
// или custom_timezone события, а не эту константу.
